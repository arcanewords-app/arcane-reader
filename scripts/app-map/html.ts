import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AppMap } from './types.js';

const here = dirname(fileURLToPath(import.meta.url));

export function renderHtml(map: AppMap): string {
  const css = readFileSync(join(here, 'viewer.css'), 'utf8');
  const js = readFileSync(join(here, 'viewer.js'), 'utf8');
  const data = JSON.stringify(map).replace(/</g, '\\u003c');
  return `<!DOCTYPE html>
<html lang="ru">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${escapeText(map.product.name)} — карта продукта</title>
  <style>
${css}
  </style>
</head>
<body>
  <!-- generated by npm run docs:app-map — do not edit -->
  <div id="app"></div>
  <script>
    const DATA = ${data};
${js}
  </script>
</body>
</html>
`;
}

function escapeText(value: string): string {
  return value.replace(/[&<>"]/g, (char) => {
    if (char === '&') return '&amp;';
    if (char === '<') return '&lt;';
    if (char === '>') return '&gt;';
    return '&quot;';
  });
}
